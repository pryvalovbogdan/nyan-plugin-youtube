export function getTranslation(lang) {
  return TRANSLATIONS[lang] || TRANSLATIONS.en;
}

export function detectBrowserLanguage() {
  const base = (navigator.language || 'en').split('-')[0];

  return TRANSLATIONS[base] ? base : 'en';
}
